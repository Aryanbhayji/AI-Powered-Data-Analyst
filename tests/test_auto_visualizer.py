"""Tests for automatic, analyst-style dataset visualizations."""

from pathlib import Path

import matplotlib
matplotlib.use("Agg")

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import pytest
from streamlit.testing.v1 import AppTest

from src.auto_visualizer import MAX_CHARTS, build_visualization_report
from src.type_inference import infer_column_types

FIXTURES = Path(__file__).parent / "fixtures"


def test_type_inference_identifies_numeric_category_date_and_identifier() -> None:
    """Classify common analyst roles needed for automatic chart selection."""
    dataframe = pd.DataFrame({
        "record_id": [f"r{index}" for index in range(12)],
        "date": pd.date_range("2025-01-01", periods=12).astype(str),
        "passed": np.resize([0, 1], 12),
        "amount": [10.5 + index for index in range(12)],
        "segment": np.resize(["A", "B"], 12),
    })

    kinds = infer_column_types(dataframe)

    assert kinds == {
        "record_id": "text_id",
        "date": "datetime",
        "passed": "binary",
        "amount": "numeric_continuous",
        "segment": "binary",
    }


def _close_report(report: object) -> None:
    """Release every chart figure generated by a report."""
    for chart in getattr(report, "charts", []):
        plt.close(chart.figure)


def test_titanic_report_selects_multiple_analyst_relevant_charts() -> None:
    """Profile relationships, distributions, categories, and missing values."""
    dataframe = pd.read_csv(FIXTURES / "titanic_sample.csv")
    before = dataframe.copy(deep=True)

    report = build_visualization_report(dataframe)

    assert 1 < len(report.charts) <= MAX_CHARTS
    titles = {chart.title for chart in report.charts}
    assert any("Distribution of" in title for title in titles)
    assert any("Numeric relationships" == title for title in titles)
    assert any("by" in title for title in titles)
    assert report.insights
    assert any("missing" in insight.casefold() for insight in report.insights)
    for chart in report.charts:
        assert chart.figure.axes
        assert any(axis.get_title() for axis in chart.figure.axes)
        assert chart.description
    pd.testing.assert_frame_equal(dataframe, before)
    _close_report(report)


def test_sales_report_adds_datetime_trend() -> None:
    """Recognize dates and plot a numeric measure across time."""
    dataframe = pd.read_csv(FIXTURES / "messy_sales.csv")

    report = build_visualization_report(dataframe)

    assert any("over date" in chart.title for chart in report.charts)
    trend = next(chart for chart in report.charts if "over date" in chart.title)
    assert len(trend.figure.axes[0].lines) >= 2
    _close_report(report)


def test_empty_and_degenerate_data_produce_explanatory_results() -> None:
    """Handle header-only, no-column, and all-null inputs without crashing."""
    empty = build_visualization_report(pd.DataFrame(columns=["value"]))
    no_columns = build_visualization_report(pd.DataFrame())
    all_null = build_visualization_report(pd.DataFrame({"value": [None, None]}))

    assert empty.charts == []
    assert "no data rows" in empty.insights[0]
    assert no_columns.charts == []
    assert "no columns" in no_columns.insights[0]
    assert all_null.charts
    assert "Missing values by column" in {
        chart.title for chart in all_null.charts
    }
    _close_report(empty)
    _close_report(no_columns)
    _close_report(all_null)


def test_single_row_and_identifier_only_data_are_safe() -> None:
    """Avoid presenting meaningless distributions for IDs or constants."""
    dataframe = pd.DataFrame({
        "record_id": ["a", "b", "c"],
        "constant": [1, 1, 1],
    })
    report = build_visualization_report(dataframe)
    single_row = build_visualization_report(pd.DataFrame({
        "category": ["only"],
        "measure": [3.0],
    }))

    assert not any("Distribution of record_id" == chart.title for chart in report.charts)
    assert not any("Distribution of constant" == chart.title for chart in report.charts)
    assert report.insights
    assert single_row.charts == []
    assert single_row.insights
    _close_report(report)
    _close_report(single_row)


def test_large_row_heavy_charts_are_sampled_and_disclosed() -> None:
    """Bound visual work for large files and disclose the sampled row count."""
    dataframe = pd.DataFrame({
        "amount": np.arange(25_000, dtype=float),
        "group": np.resize(["A", "B", "C"], 25_000),
    })

    report = build_visualization_report(dataframe)

    assert report.notices
    assert "20,000 of 25,000" in report.notices[0]
    assert report.charts
    _close_report(report)


def test_app_runs_data_story_without_request_agent(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Keep automatic visualization available after removing the request agent."""
    monkeypatch.delenv("OPENAI_API_KEY", raising=False)
    monkeypatch.delenv("ANTHROPIC_API_KEY", raising=False)
    app_path = Path(__file__).parents[1] / "app.py"
    fixture_path = Path(__file__).parent / "fixtures" / "messy_sales.csv"
    test_app = AppTest.from_file(str(app_path), default_timeout=30)
    test_app.run()
    test_app.file_uploader[0].set_value(
        ("messy_sales.csv", fixture_path.read_bytes(), "text/csv")
    ).run()

    assert not test_app.exception
    assert test_app.session_state["visualization_payload"]["charts"]
    assert not any(
        str(key).startswith("ask_") for key in test_app.session_state
    )
